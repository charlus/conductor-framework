#!/usr/bin/env node
// Capture every `.agents/` path Conductor has EVER shipped and no longer ships.
//
// WHY. `upgrade` prunes a framework file dropped upstream only when the
// install's `.checksums.json` proves Conductor delivered it. A V4 install has no
// checksums, so a retired framework file — `rules/conductor-system.md`, loaded
// in every session — was carried forward as if it were the user's own. This list
// is the ownership proof for those installs: the path shipped in `templates/`.
//
// Re-run after deleting or renaming a file in `templates/.agents/`, and commit
// the refreshed `src/retired-framework-files.json` in the same commit.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { kebabCasePath } from "../src/kebab.js";
import { listFiles } from "../src/update.js";

const root = new URL("..", import.meta.url).pathname;
const log = execFileSync(
  "git",
  ["log", "--all", "--name-only", "--format=", "--", "templates/.agents", "templates/.agent"],
  { cwd: root, encoding: "utf8", maxBuffer: 1 << 26 }
);
const current = new Set(listFiles(join(root, "templates", ".agents")));
const retired = new Set();
for (const line of log.split("\n")) {
  const m = /^templates\/\.agents?\/(.+)$/.exec(line.trim());
  if (!m) continue;
  const rel = kebabCasePath(m[1]);
  if (!current.has(rel)) retired.add(rel);
}
const out = join(root, "src", "retired-framework-files.json");
writeFileSync(out, `${JSON.stringify({
  _comment: "Generated by scripts/capture-retired-files.js from git history. Paths (kebab-case, relative to .agents/) that Conductor once shipped and no longer ships. Used only for installs with no .checksums.json.",
  files: [...retired].sort(),
}, null, 2)}\n`);
console.log(`Wrote ${retired.size} retired paths to ${out}`);

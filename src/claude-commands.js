// Claude Code slash-command bridge (ADR-0001 D5).
//
// Antigravity invokes the framework's `.agents/workflows/*.md` files directly as
// slash commands; Claude Code only discovers slash commands from `.claude/commands/*.md`.
// This module generates one thin shim per installed workflow so `/build`, `/carve`,
// `/spec-it`, ... work natively in Claude Code. Shims carry no logic — they redirect
// to the real workflow file, which stays the single source of truth shared with
// Antigravity. `/loop` is native (via `.claude/loop.md`) and does not get a shim.
//
// Shims are DERIVED from the installed workflow set on every init/upgrade, so they
// never drift: adding, renaming, or removing a workflow is reflected automatically.

import { access, mkdir, readdir, readFile, writeFile, rm } from "node:fs/promises";
import { constants as fsConstants } from "node:fs";
import { join } from "node:path";

// Marker identifying a shim we own, so cleanup never touches the user's own commands.
const MARKER = "<!-- conductor:generated-command -->";

async function exists(path) {
  try {
    await access(path, fsConstants.F_OK);
    return true;
  } catch {
    return false;
  }
}

// Pull the `description:` out of a workflow's YAML frontmatter, if present.
function extractDescription(source, fallback) {
  const fm = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (fm) {
    const line = fm[1].match(/^\s*description:\s*(.+?)\s*$/m);
    if (line) return line[1].replace(/^["']|["']$/g, "");
  }
  return fallback;
}

function shimContent(name, description) {
  return `---
description: ${description}
argument-hint: [optional context or task]
---
${MARKER}
<!-- Generated by conductor-framework. Do not edit — change the workflow instead. -->

Read and execute the Conductor workflow at \`.agents/workflows/${name}.md\`, following its instructions exactly. Re-read the full workflow file before acting; do not rely on memory.

$ARGUMENTS
`;
}

/**
 * Generate `.claude/commands/<name>.md` shims for every installed workflow.
 * Removes stale shims we previously generated for workflows that no longer exist,
 * while leaving the user's own hand-authored commands untouched.
 *
 * @param {string} targetDir project root
 * @param {{stdout?: {write: (s: string) => void}}} [opts]
 * @returns {Promise<{written: number, removed: number}>}
 */
export async function generateClaudeCommands(targetDir, opts = {}) {
  const stdout = opts.stdout;
  const workflowsDir = join(targetDir, ".agents", "workflows");
  if (!(await exists(workflowsDir))) {
    return { written: 0, removed: 0 };
  }

  const workflowFiles = (await readdir(workflowsDir)).filter((f) => f.endsWith(".md"));
  const commandsDir = join(targetDir, ".claude", "commands");
  await mkdir(commandsDir, { recursive: true });

  const liveNames = new Set();
  let written = 0;
  for (const file of workflowFiles) {
    const name = file.slice(0, -3); // strip ".md"
    liveNames.add(name);
    const source = await readFile(join(workflowsDir, file), "utf8");
    const description = extractDescription(source, `Run the Conductor ${name} workflow`);
    await writeFile(join(commandsDir, file), shimContent(name, description));
    written += 1;
  }

  // Remove shims we generated for workflows that are gone; never touch foreign files.
  let removed = 0;
  for (const file of (await readdir(commandsDir)).filter((f) => f.endsWith(".md"))) {
    const name = file.slice(0, -3);
    if (liveNames.has(name)) continue;
    const contents = await readFile(join(commandsDir, file), "utf8");
    if (contents.includes(MARKER)) {
      await rm(join(commandsDir, file));
      removed += 1;
    }
  }

  if (stdout && written > 0) {
    stdout.write(
      `  ✅ Generated ${written} Claude Code slash command${written === 1 ? "" : "s"} in .claude/commands/` +
        (removed > 0 ? ` (${removed} stale removed)` : "") +
        "\n"
    );
  }
  return { written, removed };
}

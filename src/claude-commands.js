function cliShimContent(command) {
  return `---
description: ${command.description}
argument-hint: [optional text]
---
${MARKER}
<!-- Generated by conductor-framework. Do not edit — this fronts a CLI command. -->

${command.body}
`;
}

function shimContent(name, description) {
  return `---
description: ${description}
argument-hint: [optional context or task]
---
${MARKER}
<!-- Generated by conductor-framework. Do not edit — change the workflow instead. -->

Read and execute the Conductor workflow at \`.agents/workflows/${name}.md\`, following its instructions exactly. Re-read the full workflow file before acting; do not rely on memory.

$ARGUMENTS
`;
}

/**
 * Generate `.claude/commands/<name>.md` shims for every installed workflow.
 * Removes stale shims we previously generated for workflows that no longer exist,
 * while leaving the user's own hand-authored commands untouched.
 *
 * @param {string} targetDir project root
 * @param {{stdout?: {write: (s: string) => void}}} [opts]
 * @returns {Promise<{written: number, removed: number}>}
 */
export async function generateClaudeCommands(targetDir, opts = {}) {
  const stdout = opts.stdout;
  const workflowsDir = join(targetDir, ".agents", "workflows");
  if (!(await exists(workflowsDir))) {
    return { written: 0, removed: 0 };
  }

  const workflowFiles = (await readdir(workflowsDir)).filter((f) => f.endsWith(".md"));
  const commandsDir = join(targetDir, ".claude", "commands");
  await mkdir(commandsDir, { recursive: true });

  const liveNames = new Set();
  let written = 0;
  for (const file of workflowFiles) {
    const name = file.slice(0, -3); // strip ".md"
    liveNames.add(name);
    const source = await readFile(join(workflowsDir, file), "utf8");
    const description = extractDescription(source, `Run the Conductor ${name} workflow`);
    await writeFile(join(commandsDir, file), shimContent(name, description));
    written += 1;
  }

  // CLI-backed commands, written alongside the workflow shims.
  for (const command of CLI_COMMANDS) {
    liveNames.add(command.name);
    await writeFile(join(commandsDir, `${command.name}.md`), cliShimContent(command));
    written += 1;
  }

  // Remove shims we generated for workflows that are gone; never touch foreign files.
  let removed = 0;
  for (const file of (await readdir(commandsDir)).filter((f) => f.endsWith(".md"))) {
    const name = file.slice(0, -3);
    if (liveNames.has(name)) continue;
    const contents = await readFile(join(commandsDir, file), "utf8");
    if (contents.includes(MARKER)) {
      await rm(join(commandsDir, file));
      removed += 1;
    }
  }

  if (stdout && written > 0) {
    stdout.write(
      `  ✅ Generated ${written} Claude Code slash command${written === 1 ? "" : "s"} in .claude/commands/` +
        (removed > 0 ? ` (${removed} stale removed)` : "") +
        "\n"
    );
  }
  return { written, removed };
}

// Claude Code discovers skills only from `.claude/skills/<name>/SKILL.md`. Without
// this bridge a skill that no workflow loads by path (e.g. `handoff`) could not be
// reached in Claude Code at all. Same contract as the command shims: derived on
// every init/upgrade, no logic, redirect to the real `.agents/skills/` file.
function skillShimContent(name, description) {
  // JSON.stringify yields a valid YAML double-quoted scalar, so colons and quotes
  // in the source description cannot break the frontmatter.
  return `---
name: ${name}
description: ${JSON.stringify(description)}
---
${MARKER}
<!-- Generated by conductor-framework. Do not edit — change .agents/skills/${name}/SKILL.md instead. -->

Read and follow the Conductor skill at \`.agents/skills/${name}/SKILL.md\`, and any file it references, exactly. Re-read it before acting; do not rely on memory.

$ARGUMENTS
`;
}

/**
 * Generate `.claude/skills/<name>/SKILL.md` shims for every installed skill.
 * The Claude Code skill name is the skill's folder name (already kebab-case).
 * Removes stale shims we generated; a user's own skill — including one with the
 * same name as a Conductor skill — is never overwritten or removed.
 *
 * @param {string} targetDir project root
 * @param {{stdout?: {write: (s: string) => void}}} [opts]
 * @returns {Promise<{written: number, removed: number, skipped: string[], writtenNames: string[], removedNames: string[]}>}
 */
export async function generateClaudeSkills(targetDir, opts = {}) {
  const stdout = opts.stdout;
  const skillsDir = join(targetDir, ".agents", "skills");
  if (!(await exists(skillsDir))) {
    return { written: 0, removed: 0, skipped: [], writtenNames: [], removedNames: [] };
  }

  const claudeSkillsDir = join(targetDir, ".claude", "skills");
  const liveNames = new Set();
  const skipped = [];
  const writtenNames = [];
  const removedNames = [];
  let written = 0;
  for (const name of await readdir(skillsDir)) {
    const source = join(skillsDir, name, "SKILL.md");
    if (!(await exists(source))) continue;
    liveNames.add(name);

    const shimPath = join(claudeSkillsDir, name, "SKILL.md");
    if ((await exists(shimPath)) && !(await readFile(shimPath, "utf8")).includes(MARKER)) {
      skipped.push(name);
      continue;
    }
    const description = extractDescription(await readFile(source, "utf8"), `Conductor ${name} skill`);
    await mkdir(join(claudeSkillsDir, name), { recursive: true });
    await writeFile(shimPath, skillShimContent(name, description));
    writtenNames.push(name);
    written += 1;
  }

  let removed = 0;
  if (await exists(claudeSkillsDir)) {
    for (const name of await readdir(claudeSkillsDir)) {
      if (liveNames.has(name)) continue;
      const shimPath = join(claudeSkillsDir, name, "SKILL.md");
      if (!(await exists(shimPath))) continue;
      if ((await readFile(shimPath, "utf8")).includes(MARKER)) {
        await rm(join(claudeSkillsDir, name), { recursive: true });
        removedNames.push(name);
        removed += 1;
      }
    }
  }

  if (stdout && written > 0) {
    stdout.write(
      `  ✅ Generated ${written} Claude Code skill${written === 1 ? "" : "s"} in .claude/skills/` +
        (removed > 0 ? ` (${removed} stale removed)` : "") +
        "\n"
    );
  }
  if (stdout && skipped.length > 0) {
    stdout.write(`  ⏭️  Kept your own .claude/skills/ for: ${skipped.join(", ")}\n`);
  }
  return { written, removed, skipped, writtenNames, removedNames };
}
